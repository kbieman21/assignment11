# Task 1: Plotting with Pandas

# CONNECT TO DATABASE (use the query given in the assignment instructions)
conn = sqlite3.connect('db/lesson.db')

query = """
SELECT last_name, 
       SUM(price * quantity) AS revenue 
FROM employees e 
JOIN orders o ON e.employee_id = o.employee_id 
JOIN line_items l ON o.order_id = l.order_id 
JOIN products p ON l.product_id = p.product_id 
GROUP BY e.employee_id;
"""

# LOAD DATA
employee_results = pd.read_sql_query(query, conn)

conn.close()


# DISPLAY RESULTS AND CREATE PLOT
print(employee_results)

plt.figure(figsize=(10, 6)) # Set figure size

# bar plot with employee last names on x-axis and revenue on y-axis
ax = employee_results.plot(kind='bar', x='last_name', y='revenue', legend=False)

# customize the plot
plt.title('Total Revenue Generated by Each Employee')
plt.xlabel('Employee Last Name')
plt.ylabel('Total Revenue')
plt.xticks(rotation=45)
plt.grid(axis='y')

